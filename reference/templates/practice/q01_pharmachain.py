    queue = []

    def fake_input(prompt=""):
        if not queue:
            raise RuntimeError("self-test has no answer for the prompt " + repr(prompt))
        answer = queue.pop(0)
        print(prompt + answer)
        return answer

    builtins.input = fake_input

    def run(fn, *answers):
        queue[:] = list(answers)
        print("\n>>>", fn.__name__, answers)
        return fn()

    queue[:] = ["examkey123"]
    setup_keys()

    run(add_record, "R1", "DRU1", "0", "10", "2026-13-45", "2026-01-01")
