def normalize_bytes(text, length):
    """Turns any user-typed string into an exact-length key/IV by truncating
    or zero-padding, so AES never rejects a 'wrong size' key. Use length=16
    for AES-128 (or any cipher's IV), 24 for AES-192, 32 for AES-256."""
    raw = text.encode()[:length]
    return raw.ljust(length, b"\0")


# ---------- from ciphers/schnorr_signature.py (verbatim) ----------

def _hash_to_int(*parts, modulus):
    digest = hashlib.sha256("".join(str(p) for p in parts).encode()).digest()
    return int.from_bytes(digest, "big") % modulus


def schnorr_generate_domain_parameters(q_bits=64):
    """A safe prime p = 2q + 1 gives a subgroup of prime order q that g lives in."""
    while True:
        q = getPrime(q_bits)
        p = 2 * q + 1
        if isPrime(p):
            break

    while True:
        h = getRandomRange(2, p - 1)
        g = pow(h, 2, p)
        if g != 1:
            break

    return p, q, g


def schnorr_generate_keys(p, q, g):
    x = getRandomRange(2, q - 1)   # private key
    y = pow(g, x, p)               # public key

    return y, x


def schnorr_sign(message, p, q, g, x):
    k = getRandomRange(2, q - 1)
    r = pow(g, k, p)

    e = _hash_to_int(r, message, modulus=q)
    s = (k + x * e) % q

    return str(e) + "," + str(s)


def schnorr_verify(message, signature, p, q, g, y):
    e, s = _split_signature(signature)
    r_check = (pow(g, s, p) * pow(y, -e, p)) % p
    e_check = _hash_to_int(r_check, message, modulus=q)

    return e_check == e


def _split_signature(signature):
    """A signature is the string "a,b"; numbers or a tuple (e.g. read from a file) work too."""
    if isinstance(signature, str):
        first, second = signature.split(",")
        return int(first), int(second)
    return int(signature[0]), int(signature[1])


# ---------- from ciphers/aes.py (verbatim) ----------

def aes_encrypt(key, plaintext, iv=None):
    key_bytes = key.encode() if isinstance(key, str) else key
    iv = iv or get_random_bytes(AES.block_size)

    cipher = AES.new(key_bytes, AES.MODE_CBC, iv)

    encrypted = cipher.encrypt(pad(plaintext.encode(), AES.block_size))

    return (iv + encrypted).hex()


def aes_decrypt(key, ciphertext):
    key_bytes = key.encode() if isinstance(key, str) else key

    raw = bytes.fromhex(ciphertext)
    iv, encrypted = raw[:AES.block_size], raw[AES.block_size:]

    cipher = AES.new(key_bytes, AES.MODE_CBC, iv)

    decrypted = unpad(cipher.decrypt(encrypted), AES.block_size)

    return decrypted.decode()


# ---------- from ciphers/hashing.py (verbatim) ----------

def sha512_hash(text):
    return hashlib.sha512(text.encode()).hexdigest()


