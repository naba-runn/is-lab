def add_record():
    rec_id = ask_text("Batch ID: ")
    if find_record(rec_id) is not None:
        print("Batch ID", rec_id, "already exists -- not stored again.")
        return
    drug = ask_text("Drug: ")
    quantity = ask_checked("Quantity: ", "Quantity", as_int=True)
    expiry = ask_checked("Expiry: ", "Expiry")
    plaintext = "Drug: " + drug + "\n" + "Quantity: " + str(quantity) + "\n" + "Expiry: " + expiry

    section("encrypting " + rec_id)
    step("plaintext", plaintext)
    rec = {"id": rec_id}
    rec.update(encrypt_data(plaintext))
    rec["time"] = timestamp()
    step("timestamp", rec["time"])
    step("data hashed (id|ciphertexts|time)", hashed_part(rec))
    rec["hash"] = hash_fn(hashed_part(rec))
    step("SHA-512 hash", rec["hash"])
    step("message signed (hash)", signed_part(rec))
    rec["sig"] = sign(signed_part(rec))
    step("Schnorr signature", rec["sig"])
    append_record(rec)
    section("Drug batch stored")
    show_full(rec)
    print("  (saved in " + RECORDS_FILE + ")")


