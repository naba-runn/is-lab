def add_record():
    rec_id = ask_text("Employee ID: ")
    if find_record(rec_id) is not None:
        print("Employee ID", rec_id, "already exists -- not stored again.")
        return
    name = ask_text("Name: ")
    department = ask_text("Department: ")
    salary = ask_int("Salary: ")
    multiplier = ask_int("Multiplier: ")
    plaintext = "Name: " + name + "\n" + "Department: " + department + "\n" + "Salary: " + str(salary) + "\n" + "Multiplier: " + str(multiplier)

    section("encrypting " + rec_id)
    step("plaintext", plaintext)
    rec = {"id": rec_id}
    rec.update(encrypt_data(plaintext))
    rec["p_salary"] = he_encrypt_add(salary)
    step("Paillier Enc(Salary) = g^m * r^n mod n^2", rec["p_salary"])
    rec["m_multiplier"] = he_encrypt_mul(multiplier)
    step("textbook RSA Enc(Multiplier) = multiplier^e mod n", rec["m_multiplier"])
    rec["e_multiplier"] = he_encrypt_eg(multiplier)
    step("ElGamal Enc(Multiplier) = (g^k, m*h^k) mod p", rec["e_multiplier"])
    rec["time"] = timestamp()
    step("timestamp", rec["time"])
    step("data hashed (id|ciphertexts|time)", hashed_part(rec))
    rec["hash"] = hash_fn(hashed_part(rec))
    step("SHA-256 hash", rec["hash"])
    step("message signed (hash)", signed_part(rec))
    rec["sig"] = sign(signed_part(rec))
    step("RSA signature", rec["sig"])
    append_record(rec)
    index_record(rec_id, ["name=" + name.lower(), "department=" + department.lower()], rec["time"])
    section("Employee stored")
    show_full(rec)
    print("  (saved in " + RECORDS_FILE + ")")


