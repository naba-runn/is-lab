# ---------- from ciphers/paillier.py (verbatim) ----------

def paillier_generate_keys(bits=1024):
    while True:
        p = getPrime(bits // 2)
        q = getPrime(bits // 2)
        if p != q and math.gcd(p * q, (p - 1) * (q - 1)) == 1:
            break

    n = p * q
    g = n + 1
    lam = (p - 1) * (q - 1) // math.gcd(p - 1, q - 1)       # lcm(p-1, q-1)
    mu = pow((pow(g, lam, n * n) - 1) // n, -1, n)

    return n, g, lam, mu


def paillier_encrypt(n, g, message):
    n2 = n * n

    while True:
        r = getRandomRange(1, n)
        if math.gcd(r, n) == 1:
            break

    return (pow(g, message, n2) * pow(r, n, n2)) % n2


def paillier_decrypt(n, lam, mu, ciphertext):
    l = (pow(ciphertext, lam, n * n) - 1) // n

    return (l * mu) % n


def paillier_add(n, c1, c2):
    return (c1 * c2) % (n * n)


def paillier_add_plain(n, g, ciphertext, k):
    return (ciphertext * pow(g, k % n, n * n)) % (n * n)


def paillier_subtract(n, c1, c2):
    return (c1 * pow(c2, -1, n * n)) % (n * n)


def paillier_multiply_plain(n, ciphertext, k):
    return pow(ciphertext, k, n * n)


# ---------- from ciphers/rsa_homomorphic.py (verbatim) ----------

def rsa_he_generate_keys(bits=1024):
    e = 65537

    while True:
        p = getPrime(bits // 2)
        q = getPrime(bits // 2)
        phi = (p - 1) * (q - 1)
        if p != q and math.gcd(e, phi) == 1:
            break

    d = pow(e, -1, phi)

    return p * q, e, d


def rsa_he_encrypt(n, e, message):
    return pow(message, e, n)


def rsa_he_decrypt(n, d, ciphertext):
    return pow(ciphertext, d, n)


def rsa_he_multiply(n, c1, c2):
    return (c1 * c2) % n


def rsa_he_multiply_plain(n, e, ciphertext, k):
    """Enc(m) * k^e = Enc(k * m)."""
    return (ciphertext * pow(k, e, n)) % n


def rsa_he_power(n, ciphertext, k):
    """Enc(m)^k = (m^e)^k = Enc(m^k)."""
    return pow(ciphertext, k, n)


# ---------- from ciphers/elgamal_homomorphic.py (verbatim) ----------

def elgamal_he_generate_keys(bits=512):
    p = getPrime(bits)
    g = 2
    x = getRandomRange(2, p - 1)   # private key
    h = pow(g, x, p)               # public key

    return p, g, h, x


def elgamal_he_encrypt(p, g, h, m):
    k = getRandomRange(2, p - 1)

    return pow(g, k, p), (m * pow(h, k, p)) % p


def elgamal_he_decrypt(p, x, ciphertext):
    c1, c2 = ciphertext
    s = pow(c1, x, p)

    return (c2 * pow(s, -1, p)) % p


def elgamal_he_multiply(p, ct1, ct2):
    return (ct1[0] * ct2[0]) % p, (ct1[1] * ct2[1]) % p


def elgamal_he_multiply_plain(p, ciphertext, k):
    return ciphertext[0], (ciphertext[1] * k) % p


def elgamal_he_power(p, ciphertext, k):
    return pow(ciphertext[0], k, p), pow(ciphertext[1], k, p)


def elgamal_exp_encrypt(p, g, h, m):
    return elgamal_he_encrypt(p, g, h, pow(g, m, p))


def elgamal_exp_decrypt(p, g, x, ciphertext, limit=1000000):
    target = elgamal_he_decrypt(p, x, ciphertext)      # g^m
    value = 1
    for m in range(limit):
        if value == target:
            return m
        value = (value * g) % p
    raise ValueError("sum is larger than the search limit")


# ---------- output formatting ----------

WRAP = 64          # long values (hex, big numbers) are printed in lines of this many characters


def wrap_value(value, indent):
    """Cuts a long value into WRAP-character lines; every extra line starts at column `indent`."""
    lines = []
    for line in str(value).split("\n"):
        lines += [line[i:i + WRAP] for i in range(0, len(line), WRAP)] or [""]
    return ("\n" + " " * indent).join(lines)


def section(title):
    print()
    print("  " + title.upper())
    print("  " + "-" * len(title))


def show_value(name, value, width=24):
    """One aligned 'name : value' line; a long value wraps under itself."""
    print("  " + name.ljust(width) + " : " + wrap_value(value, width + 5))


def step(name, value):
    """One intermediate value (only when SHOW_STEPS is on): the name, the value indented below it."""
    if SHOW_STEPS:
        print("    > " + name)
        print("        " + wrap_value(value, 8))
        print()


