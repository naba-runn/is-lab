# ---------- which records a homomorphic operation uses ----------

def records_for(ids):
    records = []
    for rec_id in ids:
        rec = find_record(rec_id)
        if rec is None:
            print("  ", rec_id, ": not found, skipped")
        else:
            records.append(rec)
    print("Selected:", [rec["id"] for rec in records])
    return records


def select_all():
    records = load_records()
    print("Selected: all", len(records), "records")
    return records


def select_by_ids():
    return records_for([x.strip() for x in ask_text("IDs, comma separated: ").split(",") if x.strip()])


def select_by_filter(method, field):
    value = ask_text(field + " = ")
    print("Filter", field, "=", value, "through the", method, "index")
    return records_for(index_lookup(method, field, value))


def add_const_salary():
    """Add constant k to each Salary (Paillier Enc(m) * g^k). Each new value is decrypted on its own."""
    records = select_by_filter("plain", "Department")
    k = ask_int("Constant k: ")
    results = {}
    for rec in records:
        if not is_valid(rec):
            print(rec["id"], ": failed verification, NOT included")
            continue
        c = int(rec["p_salary"])
        step("Enc(Salary) of " + rec["id"], c)
        new = paillier_add_plain(K["p_n"], K["p_g"], c, k)
        step("Enc(m) * g^k mod n^2 = Enc(m + k)", new)
        results[rec["id"]] = decrypt_total(new)
        print("  " + rec["id"] + " : Salary + k = " + str(results[rec["id"]]) + "    (k = " + str(k) + ")")
    log_access("add_const_salary", ",".join(results), str(results))
    return results


def sum_salary():
    """Homomorphic SUM of Salary (Paillier). Only the final result is decrypted."""
    records = select_by_filter("plain", "Department")
    total = paillier_encrypt(K["p_n"], K["p_g"], 0)
    step("start with Enc(0)", total)
    counted = []
    for rec in records:
        if not is_valid(rec):
            print(rec["id"], ": failed verification, NOT included")
            continue
        c = int(rec["p_salary"])
        step("Enc(Salary) of " + rec["id"], c)
        total = paillier_add(K["p_n"], total, c)
        step("encrypted total after " + rec["id"] + " (multiply mod n^2 = add plaintexts)", total)
        counted.append(rec["id"])
    if not counted:
        print("No valid records selected.")
        return None
    section("result")
    show_value("encrypted result", short(str(total), 60))
    result = decrypt_total(total)
    result_line("SUM of Salary over " + ", ".join(counted) + " = " + str(result))
    log_access("sum_salary", ",".join(counted), str(result))
    return result


def difference_salary():
    """DIFFERENCE of Salary between two records (Paillier Enc(a) / Enc(b)): Enc(a) * Enc(b)^-1 mod n^2 = Enc(a - b)."""
    first = find_record(ask_text("First ID (a): "))
    second = find_record(ask_text("Second ID (b): "))
    if first is None or second is None:
        print("Not found.")
        return None
    for rec in (first, second):
        if not is_valid(rec):
            print(rec["id"], ": failed verification -- not used.")
            return None
    ca, cb = int(first["p_salary"]), int(second["p_salary"])
    step("Enc(Salary) of " + first["id"] + " (a)", ca)
    step("Enc(Salary) of " + second["id"] + " (b)", cb)
    difference = paillier_subtract(K["p_n"], ca, cb)
    step("Enc(a) * Enc(b)^-1 mod n^2 = Enc(a - b)", difference)
    result = decrypt_total(difference)
    if result > K["p_n"] // 2:            # negative numbers decrypt as n - |value|
        result -= K["p_n"]
    result_line("Salary of " + first["id"] + " - " + second["id"] + " = " + str(result))
    log_access("difference_salary", first["id"] + "," + second["id"], str(result))
    return result


