def self_test():
    import builtins
    import tempfile
    global RECORDS_FILE, LOG_FILE, KEYS_FILE, DECRYPTED_FILE, PLAIN_INDEX_FILE, SSE_INDEX_FILE

    tmp = tempfile.mkdtemp()
    RECORDS_FILE = os.path.join(tmp, "records.txt")
    LOG_FILE = os.path.join(tmp, "log.txt")
    KEYS_FILE = os.path.join(tmp, "keys.txt")
    DECRYPTED_FILE = os.path.join(tmp, "decrypted.txt")
    PLAIN_INDEX_FILE = os.path.join(tmp, "plain_index.txt")
    SSE_INDEX_FILE = os.path.join(tmp, "sse_index.txt")

    queue = []

    def fake_input(prompt=""):
        if not queue:
            raise RuntimeError("self-test has no answer for the prompt " + repr(prompt))
        answer = queue.pop(0)
        print(prompt + answer)
        return answer

    builtins.input = fake_input

    def run(fn, *answers):
        queue[:] = list(answers)
        print("\n>>>", fn.__name__, answers)
        return fn()

    queue[:] = []
    setup_keys()

    run(add_record, "R1", "NAM1", "not-a-valid-choice", "A+", "MED1", "pw-R1")
    run(add_record, "R2", "NAM2", "A-", "MED2", "pw-R2")
    run(add_record, "R3", "NAM1", "A+", "MED1", "pw-R3")
    run(add_record, "R1")                       # duplicate ID is refused
    assert len(load_records()) == 3
    assert all(is_valid(rec) for rec in load_records())

    # restart: keys come back from KEYS_FILE, old records must still verify
    K.clear()
    queue[:] = []
    setup_keys()
    assert all(is_valid(rec) for rec in load_records())

    assert run(verify_one, "R1") is True
    run(view_meta)
    assert run(decrypt_one, "R1", "pw-R1") is not None
    assert len(open(DECRYPTED_FILE, encoding="utf-8").read().splitlines()) == 1
    assert run(decrypt_one, "R1", "not-the-password") is None             # wrong password refused
    assert len(open(DECRYPTED_FILE, encoding="utf-8").read().splitlines()) == 1   # refusals not written
    assert run(search_records, "plain", "Blood Group", "A+") == ["R1", "R3"]
    assert run(search_records, "SSE", "A+") == ["R1", "R3"]
    assert run(search_records, "SSE", "nothing-like-this") == []
    assert run(search_records, "plain", "Donor ID", "R2") == ["R2"]

    # tamper with R2: every check must now refuse it
    run(tamper_record, "R2")
    assert not is_valid(find_record("R2"))
    assert run(verify_one, "R2") is False                  # tampered -> INVALID, nothing shown
    assert run(decrypt_one, "R2") is None
    assert len(open(DECRYPTED_FILE, encoding="utf-8").read().splitlines()) == 1   # refused -> not written

    print("\nSELF-TEST PASSED")


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "test":
        self_test()
    else:
        main()
