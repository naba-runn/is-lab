def add_record():
    rec_id = ask_text("Donor ID: ")
    if find_record(rec_id) is not None:
        print("Donor ID", rec_id, "already exists -- not stored again.")
        return
    name = ask_text("Name: ")
    blood_group = ask_checked("Blood Group: ", "Blood Group")
    medical_notes = ask_text("Medical Notes: ")
    plaintext = "Name: " + name + "\n" + "Blood Group: " + blood_group + "\n" + "Medical Notes: " + medical_notes

    section("encrypting " + rec_id)
    step("plaintext", plaintext)
    rec = {"id": rec_id}
    rec.update(encrypt_data(plaintext))
    rec["time"] = timestamp()
    step("timestamp", rec["time"])
    step("data hashed (id|ciphertexts|time)", hashed_part(rec))
    rec["hash"] = hash_fn(hashed_part(rec))
    step("SHA-256 hash", rec["hash"])
    step("message signed (hash)", signed_part(rec))
    rec["sig"] = sign(signed_part(rec))
    step("RSA signature", rec["sig"])
    append_record(rec)
    index_record(rec_id, ["blood group=" + blood_group.lower()], rec["time"])
    section("Donor record stored")
    show_full(rec)
    print("  (saved in " + RECORDS_FILE + ")")


def view_meta():
    """ID, timestamp and hash only -- no ciphertext, no decryption."""
    records = load_records()
    if not records:
        print("No records yet.")
    for rec in records:
        section(ID_LABEL + " " + rec["id"])
        show_value("timestamp", rec["time"], 10)
        show_value("hash", rec["hash"], 10)
        show_value("status", status_of(check_record(rec)), 10)


def verify_one():
    """Hash + signature (+ time) of ONE record. The record's contents are never shown."""
    rec = find_record(ask_text(ID_LABEL + " to verify: "))
    if rec is None:
        print("Not found.")
        return None
    section("verifying " + rec["id"] + " (contents not shown)")
    result = check_record(rec, show=True)
    show_value("RESULT", checks_text(result) + "  ->  " + status_of(result))
    log_access("verify", rec["id"], status_of(result))
    return all(result.values())


def decrypt_one():
    rec = find_record(ask_text("Donor ID to decrypt: "))
    if rec is None:
        print("Not found.")
        return None
    section("verifying " + rec["id"] + " first")
    result = check_record(rec, show=True)
    show_value("RESULT", checks_text(result) + "  ->  " + status_of(result))
    if not all(result.values()):
        print("Verification FAILED -- refusing to decrypt.")
        log_access("decrypt", rec["id"], "DENIED")
        return None
    section("decrypting " + rec["id"])
    try:
        plaintext = decrypt_data(rec, show=True)
    except Exception as e:
        print("Decryption failed (wrong key?):", type(e).__name__, e)
        log_access("decrypt", rec["id"], "FAILED")
        return None
    section("decrypted donor record")
    for line in plaintext.split("\n"):
        print("    " + line)
    save_decrypted(rec["id"], plaintext)
    log_access("decrypt", rec["id"], "GRANTED")
    return plaintext


def search_records():
    """Plain or encrypted index lookup; prints the COMPLETE stored record of every match."""
    ids = ask_index_query()
    show_results(ids)
    log_access("search", ",".join(ids) or "-", str(len(ids)) + " match(es)")
    return ids


def tamper_record():
    """Demo only: change one character of a stored ciphertext."""
    rec_id = ask_text("ID to tamper with: ")
    records = load_records()
    for rec in records:
        if rec["id"] == rec_id:
            c = rec["enc"]
            rec["enc"] = c[:-1] + ("0" if c[-1] != "0" else "1")
            save_records(records)
            print("Changed the last character of the stored ciphertext of", rec_id)
            return
    print("Not found.")


def clear_files():
    """Fresh keys -> old records can never verify again, so start with empty files."""
    for path in (RECORDS_FILE, LOG_FILE, PLAIN_INDEX_FILE, SSE_INDEX_FILE, DECRYPTED_FILE):
        if os.path.exists(path):
            os.remove(path)


