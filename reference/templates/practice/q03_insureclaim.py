def self_test():
    import builtins
    import tempfile
    global RECORDS_FILE, LOG_FILE, KEYS_FILE, DECRYPTED_FILE, PLAIN_INDEX_FILE

    tmp = tempfile.mkdtemp()
    RECORDS_FILE = os.path.join(tmp, "records.txt")
    LOG_FILE = os.path.join(tmp, "log.txt")
    KEYS_FILE = os.path.join(tmp, "keys.txt")
    DECRYPTED_FILE = os.path.join(tmp, "decrypted.txt")
    PLAIN_INDEX_FILE = os.path.join(tmp, "plain_index.txt")

    queue = []

    def fake_input(prompt=""):
        if not queue:
            raise RuntimeError("self-test has no answer for the prompt " + repr(prompt))
        answer = queue.pop(0)
        print(prompt + answer)
        return answer

    builtins.input = fake_input

    def run(fn, *answers):
        queue[:] = list(answers)
        print("\n>>>", fn.__name__, answers)
        return fn()

    queue[:] = []
    setup_keys()

    run(add_record, "R1", "REG1", "DES1", "10")
    run(add_record, "R2", "REG2", "DES2", "20")
    run(add_record, "R3", "REG1", "DES1", "30")
    run(add_record, "R1")                       # duplicate ID is refused
    assert len(load_records()) == 3
    assert all(is_valid(rec) for rec in load_records())

    # restart: keys come back from KEYS_FILE, old records must still verify
    K.clear()
    queue[:] = []
    setup_keys()
    assert all(is_valid(rec) for rec in load_records())

    assert run(verify_one, "R1") is True
    assert run(decrypt_one, "R1") is not None
    assert len(open(DECRYPTED_FILE, encoding="utf-8").read().splitlines()) == 1
    assert run(compare_amount, "R1, R3", "15") == {"R1": False, "R3": True}          # typed IDs
    assert run(sum_amount, "REG1") == 40          # fixed filter Region via plain
    assert run(average_amount, "REG1") == 20.0          # fixed filter Region via plain
    assert run(scaled_sum_amount, "R1, R3", "3") == 120          # typed IDs

    # tamper with R2: every check must now refuse it
    run(tamper_record, "R2")
    assert not is_valid(find_record("R2"))
    assert run(verify_one, "R2") is False                  # tampered -> INVALID, nothing shown
    assert run(decrypt_one, "R2") is None
