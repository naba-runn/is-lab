def select_by_filter(method, field):
    value = ask_text(field + " = ")
    print("Filter", field, "=", value, "through the", method, "index")
    return records_for(index_lookup(method, field, value))


def compare_amount():
    """Is Amount above a threshold? (Paillier subtract + blind, value hidden): Enc(m - T) blinded by a random r > 0; only the SIGN is learned, never m."""
    records = select_by_ids()
    threshold = ask_int("Threshold T: ")
    results = {}
    for rec in records:
        if not is_valid(rec):
            print(rec["id"], ": failed verification, NOT included")
            continue
        c = int(rec["p_amount"])
        step("Enc(Amount) of " + rec["id"], c)
        difference = paillier_add_plain(K["p_n"], K["p_g"], c, -threshold)
        step("Enc(m) * g^-T = Enc(m - T)", difference)
        blinded = paillier_multiply_plain(K["p_n"], difference, getRandomRange(1, 2 ** 32))
        step("Enc((m - T) * r), r random", blinded)
        value = decrypt_total(blinded)
        if value > K["p_n"] // 2:
            value -= K["p_n"]
        step("decrypted blinded value (only its sign means anything)", value)
        results[rec["id"]] = value > 0
        print("  " + rec["id"] + " : Amount " + ("ABOVE " if value > 0 else "NOT above ") + str(threshold))
    log_access("compare_amount", ",".join(results), str(results))
    return results


def sum_amount():
    """Homomorphic SUM of Amount (Paillier). Only the final result is decrypted."""
    records = select_by_filter("plain", "Region")
    total = paillier_encrypt(K["p_n"], K["p_g"], 0)
    step("start with Enc(0)", total)
    counted = []
    for rec in records:
        if not is_valid(rec):
            print(rec["id"], ": failed verification, NOT included")
            continue
        c = int(rec["p_amount"])
        step("Enc(Amount) of " + rec["id"], c)
        total = paillier_add(K["p_n"], total, c)
        step("encrypted total after " + rec["id"] + " (multiply mod n^2 = add plaintexts)", total)
        counted.append(rec["id"])
    if not counted:
        print("No valid records selected.")
        return None
    section("result")
    show_value("encrypted result", short(str(total), 60))
    result = decrypt_total(total)
    result_line("SUM of Amount over " + ", ".join(counted) + " = " + str(result))
    log_access("sum_amount", ",".join(counted), str(result))
    return result


