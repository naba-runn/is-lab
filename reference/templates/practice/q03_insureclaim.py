    assert run(compare_amount, "R1, R2, R3", "15") == {"R1": False, "R3": True}                 # R2 no longer counted
    assert run(sum_amount, "REG1") == 40                 # R2 no longer counted
    assert run(average_amount, "REG1") == 20.0                 # R2 no longer counted
    assert run(scaled_sum_amount, "R1, R2, R3", "3") == 120                 # R2 no longer counted

    print("\nSELF-TEST PASSED")


