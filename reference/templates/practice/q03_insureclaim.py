K = {}


def setup_keys():
    if os.path.exists(KEYS_FILE):
        load_keys()
        print("Keys loaded from", KEYS_FILE, "-- the same keys as the earlier runs.")
        return
    print("Generating keys (a few seconds)...")
    K["rsa_priv"], K["rsa_pub"], K["rsa_n"], K["rsa_e"], K["rsa_d"] = rsa_generate_keys()
    print("RSA public key: n =", K["rsa_n"], " e =", K["rsa_e"])
    K["p_n"], K["p_g"], K["p_lam"], K["p_mu"] = paillier_generate_keys(1024)
    print("Paillier public key: n =", K["p_n"], " g = n + 1")
    save_keys()
    print("Keys saved to", KEYS_FILE, "-- later runs reuse them.")
    print("Keys ready.")


# ==================== EDIT ZONE 1: which crypto ====================
# Every crypto call goes through these functions. Stored values are
# strings, so int() happens HERE only.

def encrypt_data(plaintext):
    """AES-256-CBC. Returns the fields to store."""
    key = get_random_bytes(32)                  # fresh key for every record
    step("AES-256 key (hex)", key.hex())
    iv = None                                   # None -> a fresh random IV
    ciphertext = aes_encrypt(key, plaintext, iv)
    step("IV (hex) = first 32 hex chars of the ciphertext", ciphertext[:32])
    step("AES-256-CBC ciphertext (hex)", ciphertext)
    fields = {"enc": ciphertext}
    fields["key"] = rsa_encrypt(K["rsa_pub"], key.hex())    # RSA-wrapped key
    step("AES-256 key encrypted with the RSA public key", fields["key"])
    return fields


def decrypt_data(rec, show=True):
    key = bytes.fromhex(rsa_decrypt(K["rsa_priv"], rec["key"]))    # unwrap the key first
    if show:
        step("AES-256 key recovered with the RSA private key (hex)", key.hex())
    plaintext = aes_decrypt(key, rec["enc"])
    if show:
        step("decrypted plaintext", plaintext)
    return plaintext


def hash_fn(text):
    return sha256_hash(text)


def sign(message):
    return rsa_sign(message, K["rsa_d"], K["rsa_n"])


def verify_sig(signature, message, show=False):
    if show:
        step("signature^e mod n (with the public key)", pow(int(signature), K["rsa_e"], K["rsa_n"]))
        step("SHA-256 of the message mod n (must be equal)", rsa_message_number(message, K["rsa_n"]))
    return rsa_verify(message, signature, K["rsa_e"], K["rsa_n"])


def he_encrypt_add(x):
    """Paillier: Enc(a) * Enc(b) mod n^2 = Enc(a + b)."""
    return str(paillier_encrypt(K["p_n"], K["p_g"], x))


def decrypt_total(total):
    result = paillier_decrypt(K["p_n"], K["p_lam"], K["p_mu"], total)
    step("Paillier decryption L(c^lambda mod n^2) * mu mod n", result)
    return result


# ==================== EDIT ZONE 2: what is hashed and signed ====================

def hashed_part(rec):
    """Everything except hash and signature -> changing ANY stored value is detected."""
    return "|".join(rec[name] for name in FIELDS if name not in ("hash", "sig"))


def recompute_hash(rec, show=False):
    data = hashed_part(rec)
    if show:
        step("data hashed (id|ciphertexts|time)", data)
    return hash_fn(data)


def signed_part(rec):
    """Only the hash is signed. The timestamp is still protected: it is part of the hashed data."""
    return rec["hash"]


def check_record(rec, show=False):
    """{check name: True/False} -- never raises. show=True prints every value compared."""
    result = {}
    try:
        recomputed = recompute_hash(rec, show)
        result["hash"] = recomputed == rec["hash"]
    except Exception as e:
        recomputed = "(could not recompute: " + type(e).__name__ + ")"
        result["hash"] = False
    if show:
        show_value("hash received (sender)", rec["hash"])
        show_value("hash recomputed (now)", recomputed)
        show_value("hashes match", result["hash"])
    try:
        if show:
            step("signature received", rec["sig"])
            step("message it must cover (hash)", signed_part(rec))
        result["signature"] = verify_sig(rec["sig"], signed_part(rec), show)
    except Exception:
        result["signature"] = False
    if show:
        show_value("signature valid", result["signature"])
    return result


def is_valid(rec):
    return all(check_record(rec).values())


