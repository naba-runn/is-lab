# ---------- from ciphers/aes.py (verbatim) ----------

def aes_encrypt(key, plaintext, iv=None):
    key_bytes = key.encode() if isinstance(key, str) else key
    iv = iv or get_random_bytes(AES.block_size)

    cipher = AES.new(key_bytes, AES.MODE_CBC, iv)

    encrypted = cipher.encrypt(pad(plaintext.encode(), AES.block_size))

    return (iv + encrypted).hex()


def aes_decrypt(key, ciphertext):
    key_bytes = key.encode() if isinstance(key, str) else key

    raw = bytes.fromhex(ciphertext)
    iv, encrypted = raw[:AES.block_size], raw[AES.block_size:]

    cipher = AES.new(key_bytes, AES.MODE_CBC, iv)

    decrypted = unpad(cipher.decrypt(encrypted), AES.block_size)

    return decrypted.decode()


# ---------- from ciphers/rsa.py (verbatim) ----------

def rsa_generate_keys():
    private_key = rsa.generate_private_key(
        public_exponent=65537,
        key_size=2048
    )
    public_key = private_key.public_key()

    numbers = private_key.private_numbers()

    n = numbers.public_numbers.n
    e = numbers.public_numbers.e
    d = numbers.d

    return private_key, public_key, n, e, d


def rsa_encrypt(public_key, message):
    ciphertext = public_key.encrypt(
        message.encode(),
        padding.OAEP(
            mgf=padding.MGF1(hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None
        )
    )

    return ciphertext.hex()


def rsa_decrypt(private_key, ciphertext):
    decrypted = private_key.decrypt(
        bytes.fromhex(ciphertext),
        padding.OAEP(
            mgf=padding.MGF1(hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None
        )
    )

    return decrypted.decode()


# ---------- from ciphers/rsa_signature.py (verbatim) ----------

def rsa_message_number(message, n):
    """What is actually signed: SHA-256 of the message as a number, reduced mod n."""
    return int.from_bytes(hashlib.sha256(message.encode()).digest(), "big") % n


def rsa_sign(message, d, n):
    return str(pow(rsa_message_number(message, n), d, n))


def rsa_verify(message, signature, e, n):
    return pow(int(signature), e, n) == rsa_message_number(message, n)


# ---------- from ciphers/hashing.py (verbatim) ----------

def sha256_hash(text):
    return hashlib.sha256(text.encode()).hexdigest()


# ---------- from ciphers/paillier.py (verbatim) ----------

def paillier_generate_keys(bits=1024):
    while True:
        p = getPrime(bits // 2)
        q = getPrime(bits // 2)
        if p != q and math.gcd(p * q, (p - 1) * (q - 1)) == 1:
            break

    n = p * q
    g = n + 1
    lam = (p - 1) * (q - 1) // math.gcd(p - 1, q - 1)       # lcm(p-1, q-1)
    mu = pow((pow(g, lam, n * n) - 1) // n, -1, n)

    return n, g, lam, mu


def paillier_encrypt(n, g, message):
    n2 = n * n

    while True:
        r = getRandomRange(1, n)
        if math.gcd(r, n) == 1:
            break

    return (pow(g, message, n2) * pow(r, n, n2)) % n2


def paillier_decrypt(n, lam, mu, ciphertext):
    l = (pow(ciphertext, lam, n * n) - 1) // n

    return (l * mu) % n


def paillier_add(n, c1, c2):
    return (c1 * c2) % (n * n)


def paillier_add_plain(n, g, ciphertext, k):
    return (ciphertext * pow(g, k % n, n * n)) % (n * n)


def paillier_subtract(n, c1, c2):
    return (c1 * pow(c2, -1, n * n)) % (n * n)


def paillier_multiply_plain(n, ciphertext, k):
    return pow(ciphertext, k, n * n)


# ---------- output formatting ----------

WRAP = 64          # long values (hex, big numbers) are printed in lines of this many characters


def wrap_value(value, indent):
    """Cuts a long value into WRAP-character lines; every extra line starts at column `indent`."""
    lines = []
    for line in str(value).split("\n"):
        lines += [line[i:i + WRAP] for i in range(0, len(line), WRAP)] or [""]
    return ("\n" + " " * indent).join(lines)


def section(title):
    print()
    print("  " + title.upper())
    print("  " + "-" * len(title))


def show_value(name, value, width=24):
    """One aligned 'name : value' line; a long value wraps under itself."""
    print("  " + name.ljust(width) + " : " + wrap_value(value, width + 5))


def step(name, value):
    """One intermediate value (only when SHOW_STEPS is on): the name, the value indented below it."""
    if SHOW_STEPS:
        print("    > " + name)
        print("        " + wrap_value(value, 8))
        print()


