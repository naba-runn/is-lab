def self_test():
    import builtins
    import tempfile
    global RECORDS_FILE, LOG_FILE, KEYS_FILE, PLAIN_INDEX_FILE, SSE_INDEX_FILE, PKSE_INDEX_FILE

    tmp = tempfile.mkdtemp()
    RECORDS_FILE = os.path.join(tmp, "records.txt")
    LOG_FILE = os.path.join(tmp, "log.txt")
    KEYS_FILE = os.path.join(tmp, "keys.txt")
    PLAIN_INDEX_FILE = os.path.join(tmp, "plain_index.txt")
    SSE_INDEX_FILE = os.path.join(tmp, "sse_index.txt")
    PKSE_INDEX_FILE = os.path.join(tmp, "pkse_index.txt")
    hour_ago = (datetime.now() - timedelta(hours=1)).strftime("%Y-%m-%d %H:%M")
    hour_later = (datetime.now() + timedelta(hours=1)).strftime("%Y-%m-%d %H:%M")

    queue = []

    def fake_input(prompt=""):
        if not queue:
            raise RuntimeError("self-test has no answer for the prompt " + repr(prompt))
        answer = queue.pop(0)
        print(prompt + answer)
        return answer

    builtins.input = fake_input

    def run(fn, *answers):
        queue[:] = list(answers)
        print("\n>>>", fn.__name__, answers)
        return fn()

    queue[:] = ["", ""]
    setup_keys()

    run(add_record, "R1", "YES", "WAR1")
    run(add_record, "R2", "NO", "WAR2")
    run(add_record, "R3", "YES", "WAR1")
    run(add_record, "R1")                       # duplicate ID is refused
    assert len(load_records()) == 3
    assert all(is_valid(rec) for rec in load_records())

    # restart: keys come back from KEYS_FILE, old records must still verify
    K.clear()
    queue[:] = []
    setup_keys()
    assert all(is_valid(rec) for rec in load_records())

    run(view_meta)
    run(verify_all)
    assert run(search_records, "plain", "Ward", "WAR1") == ["R1", "R3"]
    assert run(search_records, "SSE", "WAR1") == ["R1", "R3"]
    assert run(search_records, "PKSE", "WAR1") == ["R1", "R3"]
    assert run(search_records, "PKSE", "nothing-like-this") == []
    assert run(search_records, "plain", "Voter ID", "R2") == ["R2"]
    assert run(search_time_range, "plain", hour_ago, hour_later) == ["R1", "R2", "R3"]
    assert run(search_time_range, "SSE", hour_ago, hour_later) == ["R1", "R2", "R3"]
    assert run(votes_choice) == {"YES": 2, "NO": 1, "ABSTAIN": 0}                      # always all records

    # tamper with R2: every check must now refuse it
    run(tamper_record, "R2")
    assert not is_valid(find_record("R2"))
    run(verify_all)
    assert run(votes_choice) == {"YES": 2, "NO": 0, "ABSTAIN": 0}                 # R2 no longer counted

    print("\nSELF-TEST PASSED")


if __name__ == "__main__":
    if len(sys.argv) > 1 and sys.argv[1] == "test":
        self_test()
    else:
        main()
