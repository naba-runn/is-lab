def add_record():
    rec_id = ask_text("Voter ID: ")
    if find_record(rec_id) is not None:
        print("Voter ID", rec_id, "already exists -- not stored again.")
        return
    choice = ask_choice("Choice", CHOICES)
    ward = ask_text("Ward: ")
    plaintext = "Choice: " + choice + "\n" + "Ward: " + ward

    section("encrypting " + rec_id)
    step("plaintext", plaintext)
    rec = {"id": rec_id}
    rec.update(encrypt_data(plaintext))
    rec["votes"] = encrypt_vote(choice)
    step("Paillier one-hot ballot (Enc per option, ; separated)", rec["votes"])
    rec["time"] = timestamp()
    step("timestamp", rec["time"])
    step("data hashed (the plaintext)", plaintext)
    rec["hash"] = hash_fn(plaintext)
    step("SHA-256 hash", rec["hash"])
    step("message signed (hash|time)", signed_part(rec))
    rec["sig"] = sign(signed_part(rec))
    step("RSA signature", rec["sig"])
    append_record(rec)
    index_record(rec_id, ["ward=" + ward.lower()], rec["time"])
    if not K["start"] <= rec["time"][:16] <= K["end"]:
        print("WARNING: outside the polling window -- this ballot will fail verification.")
    section("Ballot stored")
    show_full(rec)
    print("  (saved in " + RECORDS_FILE + ")")


def view_meta():
    """ID, timestamp and hash only -- no ciphertext, no decryption."""
    records = load_records()
    if not records:
        print("No records yet.")
    for rec in records:
        section(ID_LABEL + " " + rec["id"])
        show_value("timestamp", rec["time"], 10)
        show_value("hash", rec["hash"], 10)
        show_value("status", status_of(check_record(rec)), 10)


def verify_all():
    records = load_records()
    if not records:
        print("No records yet.")
    for rec in records:
        section("verifying " + rec["id"])
        result = check_record(rec, show=True)
        show_value("RESULT", checks_text(result) + "  ->  " + status_of(result))
        log_access("verify", rec["id"], status_of(result))


