def add_record():
    rec_id = ask_text("Meter ID: ")
    if find_record(rec_id) is not None:
        print("Meter ID", rec_id, "already exists -- not stored again.")
        return
    zone = ask_text("Zone: ")
    reading = ask_int("Reading: ")
    plaintext = "Zone: " + zone + "\n" + "Reading: " + str(reading)

    section("encrypting " + rec_id)
    step("plaintext", plaintext)
    rec = {"id": rec_id}
    rec.update(encrypt_data(plaintext))
    rec["p_reading"] = he_encrypt_add(reading)
    step("Paillier Enc(Reading) = g^m * r^n mod n^2", rec["p_reading"])
    rec["time"] = timestamp()
    step("timestamp", rec["time"])
    step("data hashed (id|ciphertexts|time)", hashed_part(rec))
    rec["hash"] = hash_fn(hashed_part(rec))
    step("SHA-1 hash", rec["hash"])
    step("message signed (hash)", signed_part(rec))
    rec["sig"] = sign(signed_part(rec))
    step("DSA signature", rec["sig"])
    append_record(rec)
    index_record(rec_id, ["zone=" + zone.lower()], rec["time"])
    section("Reading stored")
    show_full(rec)
    print("  (saved in " + RECORDS_FILE + ")")


def verify_all():
    records = load_records()
    if not records:
        print("No records yet.")
    for rec in records:
        section("verifying " + rec["id"])
        result = check_record(rec, show=True)
        show_value("RESULT", checks_text(result) + "  ->  " + status_of(result))
        log_access("verify", rec["id"], status_of(result))


