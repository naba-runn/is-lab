# ---------- from ciphers/dh_signature.py (verbatim) ----------

def _hash_to_int(message, modulus):
    digest = hashlib.sha256(message.encode()).digest()
    return int.from_bytes(digest, "big") % modulus


def dh_generate_domain_parameters(q_bits=64, p_bits=256):
    while True:
        q = getPrime(q_bits)

        for _ in range(200):
            k = getRandomRange(2 ** (p_bits - q_bits - 1), 2 ** (p_bits - q_bits))
            p = k * q + 1
            if isPrime(p):
                break
        else:
            continue
        break

    while True:
        h = getRandomRange(2, p - 1)
        g = pow(h, (p - 1) // q, p)
        if g != 1:
            break

    return p, q, g


def dh_generate_keys(p, q, g):
    x = getRandomRange(2, q - 1)   # private key
    y = pow(g, x, p)               # public key

    return y, x


def dh_sign(message, p, q, g, x):
    h = _hash_to_int(message, q)

    while True:
        k = getRandomRange(2, q - 1)
        r = pow(g, k, p) % q
        if r == 0:
            continue

        k_inv = pow(k, -1, q)
        s = (k_inv * (h + x * r)) % q
        if s != 0:
            break

    return str(r) + "," + str(s)


def dh_verify(message, signature, p, q, g, y):
    r, s = _split_signature(signature)
    if not (0 < r < q and 0 < s < q):
        return False

    h = _hash_to_int(message, q)
    w = pow(s, -1, q)

    u1 = (h * w) % q
    u2 = (r * w) % q
    v = ((pow(g, u1, p) * pow(y, u2, p)) % p) % q

    return v == r


def _split_signature(signature):
    """A signature is the string "a,b"; numbers or a tuple (e.g. read from a file) work too."""
    if isinstance(signature, str):
        first, second = signature.split(",")
        return int(first), int(second)
    return int(signature[0]), int(signature[1])


# ---------- from ciphers/tripledes.py (verbatim) ----------

def _split_key(key_hex):
    raw = bytes.fromhex(key_hex)
    return raw[:8], raw[8:16], raw[16:24]


def _ede_encrypt_block(block, k1, k2, k3):
    block = DES.new(k1, DES.MODE_ECB).encrypt(block)
    block = DES.new(k2, DES.MODE_ECB).decrypt(block)
    block = DES.new(k3, DES.MODE_ECB).encrypt(block)
    return block


def _ede_decrypt_block(block, k1, k2, k3):
    block = DES.new(k3, DES.MODE_ECB).decrypt(block)
    block = DES.new(k2, DES.MODE_ECB).encrypt(block)
    block = DES.new(k1, DES.MODE_ECB).decrypt(block)
    return block


def tripledes_encrypt(key_hex, plaintext):
    k1, k2, k3 = _split_key(key_hex)
    padded = pad(plaintext.encode(), DES.block_size)

    encrypted = b"".join(
        _ede_encrypt_block(padded[i:i + 8], k1, k2, k3)
        for i in range(0, len(padded), 8)
    )
    return encrypted.hex()


def tripledes_decrypt(key_hex, ciphertext):
    k1, k2, k3 = _split_key(key_hex)
    raw = bytes.fromhex(ciphertext)

    decrypted = b"".join(
        _ede_decrypt_block(raw[i:i + 8], k1, k2, k3)
        for i in range(0, len(raw), 8)
    )
    return unpad(decrypted, DES.block_size).decode()


# ---------- from ciphers/rsa.py (verbatim) ----------

def rsa_generate_keys():
    private_key = rsa.generate_private_key(
        public_exponent=65537,
        key_size=2048
    )
    public_key = private_key.public_key()

    numbers = private_key.private_numbers()

    n = numbers.public_numbers.n
    e = numbers.public_numbers.e
    d = numbers.d

    return private_key, public_key, n, e, d


def rsa_encrypt(public_key, message):
    ciphertext = public_key.encrypt(
        message.encode(),
        padding.OAEP(
            mgf=padding.MGF1(hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None
        )
    )

    return ciphertext.hex()


def rsa_decrypt(private_key, ciphertext):
    decrypted = private_key.decrypt(
        bytes.fromhex(ciphertext),
        padding.OAEP(
            mgf=padding.MGF1(hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None
        )
    )

    return decrypted.decode()


