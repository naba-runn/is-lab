    rec["x_amount"] = he_encrypt_egx(amount)
    step("exponential ElGamal Enc(g^Amount) = (g^k, g^m*h^k) mod p", rec["x_amount"])
    rec["e_amount"] = he_encrypt_eg(amount)
    step("ElGamal Enc(Amount) = (g^k, m*h^k) mod p", rec["e_amount"])
    rec["p_amount"] = he_encrypt_add(amount)
    step("Paillier Enc(Amount) = g^m * r^n mod n^2", rec["p_amount"])
    rec["time"] = timestamp()
    step("timestamp", rec["time"])
    step("data hashed (id|ciphertexts|time)", hashed_part(rec))
    rec["hash"] = hash_fn(hashed_part(rec))
    step("SHA-256 hash", rec["hash"])
    step("message signed (hash)", signed_part(rec))
    rec["sig"] = sign(signed_part(rec))
    step("ElGamal signature", rec["sig"])
    append_record(rec)
    index_record(rec_id, ["company=" + company.lower()], rec["time"])
    if not K["start"] <= rec["time"][:16] <= K["end"]:
        print("WARNING: outside the bidding window -- this bid will fail verification.")
    section("Bid stored")
    show_full(rec)
    print("  (saved in " + RECORDS_FILE + ")")


