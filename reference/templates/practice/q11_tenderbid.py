def eg_sum_amount():
    """Homomorphic SUM of Amount (exponential ElGamal g^m). Only the final result is decrypted."""
    records = select_all()
    total = elgamal_exp_encrypt(K["eg_p"], K["eg_g"], K["eg_h"], 0)
    step("start with Enc(0)", total)
    counted = []
    for rec in records:
        if not is_valid(rec):
            print(rec["id"], ": failed verification, NOT included")
            continue
        c = eg_parse(rec["x_amount"])
        step("Enc(Amount) of " + rec["id"], c)
        total = elgamal_he_multiply(K["eg_p"], total, c)
        step("encrypted total after " + rec["id"] + " (g^a * g^b = g^(a+b): adds the exponents)", total)
        counted.append(rec["id"])
    if not counted:
        print("No valid records selected.")
        return None
    section("result")
    show_value("encrypted result", short(str(total), 60))
    result = elgamal_exp_decrypt(K["eg_p"], K["eg_g"], K["eg_x"], total)
    step("decrypted with the private key", result)
    result_line("SUM of Amount over " + ", ".join(counted) + " = " + str(result))
    log_access("eg_sum_amount", ",".join(counted), str(result))
    return result


