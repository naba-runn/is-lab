    K["p_n"], K["p_g"], K["p_lam"], K["p_mu"] = paillier_generate_keys(1024)
    print("Paillier public key: n =", K["p_n"], " g = n + 1")
    K["eg_p"], K["eg_g"], K["eg_h"], K["eg_x"] = elgamal_he_generate_keys()
    print("ElGamal (homomorphic) public key: p =", K["eg_p"], " g =", K["eg_g"], " h =", K["eg_h"])
